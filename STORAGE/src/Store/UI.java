    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
           
   if (jComboBox4.getSelectedIndex() == 0 ||
        jComboBox5.getSelectedIndex() == 0 ||
        jComboBox6.getSelectedIndex() == 0) {

        jTextArea1.setText("Error: Please select meal, drink, and payment!");
        return;
    }

    int foodQuantity = (int) jSpinner1.getValue();
    int drinkQuantity = (int) jSpinner2.getValue();

    // 2. Harangan ang negative values
    if (foodQuantity < 0 || drinkQuantity < 0) {
        jTextArea1.setText("Error: Quantity cannot be negative!");
        return;
    }

    // Optional: Harangan kung PAREHONG zero ang inorder
    if (foodQuantity == 0 && drinkQuantity == 0) {
        jTextArea1.setText("Error: Please order at least 1 item!");
        return;
    }

    String paymentStr = jComboBox6.getSelectedItem().toString().replace(" ", "_");

    FOOD food = FOOD.valueOf(jComboBox4.getSelectedItem().toString());
    DRINK drink = DRINK.valueOf(jComboBox5.getSelectedItem().toString());
    PAYMENTMETHOD payment = PAYMENTMETHOD.valueOf(paymentStr);

    order = new SUB1(food, drink, payment, foodQuantity, drinkQuantity);

    jTextArea1.setText("Order Created!");
    }//GEN-LAST:event_jButton1ActionPerformed

