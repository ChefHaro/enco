    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
   if (order != null) {

        int foodQuantity = (int) jSpinner1.getValue();
        int drinkQuantity = (int) jSpinner2.getValue();

        // Harangan ang negative
        if (foodQuantity < 0 || drinkQuantity < 0) {
            jTextArea1.setText("Error: Quantity cannot be negative!");
            return;
        }

        if (foodQuantity == 0 && drinkQuantity == 0) {
            jTextArea1.setText("Error: Cannot update order to 0 items!");
            return;
        }

        String paymentStr = jComboBox6.getSelectedItem().toString().replace(" ", "_");

        FOOD food = FOOD.valueOf(jComboBox4.getSelectedItem().toString());
        DRINK drink = DRINK.valueOf(jComboBox5.getSelectedItem().toString());
        PAYMENTMETHOD payment = PAYMENTMETHOD.valueOf(paymentStr);

        SUB2 update = new SUB2(
            order.getfood(),
            order.getdrink(),
            order.getpayment(),
            order.getquantity(),
            order.getDrinkQuantity()
        );

        update.updateOrder(food, drink, payment, foodQuantity, drinkQuantity);

        order = update;
        jTextArea1.setText("Order Updated!");

    } else {
        jTextArea1.setText("No order to update!");
    }
    }//GEN-LAST:event_jButton3ActionPerformed

